/** একটা <select>-এ উপজেলা ভরে দেয় (জেলা অনুযায়ী) */
export function fillUpazilaSelect(selectEl, district, placeholder = 'উপজেলা (ঐচ্ছিক)') {
  if (!selectEl) return;
  selectEl.innerHTML = `<option value="">${placeholder}</option>`;
  (UPAZILAS[district] || []).forEach(u => {
    const o = document.createElement('option');
    o.textContent = u; o.value = u;
    selectEl.appendChild(o);
  });
}

